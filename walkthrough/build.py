"""Build the interactive walkthrough from walkthrough/data.json.

    python walkthrough/export.py   # run the repo code, write data.json
    python walkthrough/build.py    # write docs/walkthrough.js and docs/walkthrough.html

The page replays data.json; it does not re-calculate anything. To show it on a web page:
  <div id="wb-walkthrough"></div>
  <script defer src="https://cdn.jsdelivr.net/gh/henfredpietersen/wordpress-content-brief-writer@<commit>/docs/walkthrough.js">
  </script>
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HERE = ROOT / "walkthrough"

HEADER = """/* Interactive walkthrough for wordpress-content-brief-writer.
   Built AI-assisted under Henfred Pietersen's direction.
   Generated by walkthrough/build.py from walkthrough/data.json; do not edit by hand. */
(function () {
  "use strict";
  var host = document.getElementById("wb-walkthrough");
  if (!host || host.shadowRoot) return;
  var D = __DATA__;
  var root = host.attachShadow({ mode: "open" });
  host.style.minHeight = "";
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function $(sel) { return root.querySelector(sel); }
  function $$(sel) { return Array.prototype.slice.call(root.querySelectorAll(sel)); }
"""

STANDALONE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>An AI researcher that can only cite what it read</title>
<style>html,body{margin:0;background:#05070d}</style></head>
<body>
<div id="wb-walkthrough"></div>
<script>
{script}</script>
</body></html>
"""


def main() -> int:
    data = json.loads((HERE / "data.json").read_text())
    payload = json.dumps(data, separators=(",", ":"), sort_keys=True, ensure_ascii=True).replace(
        "</", "<\\/"
    )
    script = (
        HEADER.replace("__DATA__", payload)
        + (HERE / "styles.js").read_text()
        + (HERE / "page_body.js").read_text()
        + "})();\n"
    )
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "walkthrough.js").write_text(script)
    (docs / "walkthrough.html").write_text(STANDALONE.replace("{script}", script))
    print(f"Wrote docs/walkthrough.js ({len(script):,} bytes) and docs/walkthrough.html")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
